#!/usr/bin/env node
/**
 * Builds src/data/landmarks-levant.json — structures that still stand, drawn on
 * the map at their true size.
 *
 *   node scripts/build-landmarks.mjs [--refetch]
 *
 * Everything else on this map is either a point (a city dot) or a reconstruction
 * (schematic town plans, contour-derived shorelines). This file is for the few
 * things that need neither caveat: standing masonry, surveyed to the centimetre,
 * that a first-century visitor would recognise.
 *
 * The Temple Mount platform is the case that justifies the layer. Herod's
 * retaining walls — the western wall among them — survive to their original
 * courses, so the platform outline in OpenStreetMap *is* the first-century
 * outline. It is also the only structure in the Gospels' Jerusalem large enough
 * to read on the map at all: 488 m along the west wall is 1.14 viewBox units at
 * this projection, about 36 px at the k=32 ceiling, where a village is 22.
 *
 * NOT INCLUDED, deliberately: the Old City walls. Those are Ottoman, built by
 * Suleiman in 1538, and follow a line that is not the first-century one. Drawing
 * them here would put a sixteenth-century wall on a first-century map — exactly
 * the error this atlas keeps finding in its own inherited data. Herod's city
 * walls are a reconstruction and belong in the town plan, marked as such.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT  = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT   = join(ROOT, 'src/data/landmarks-levant.json')
const CACHE = join(ROOT, 'scripts/.landmarks-cache.json')
const REFETCH = process.argv.includes('--refetch')
const P = 1e5                                  // 5 dp — ~1 m, right for masonry
const round = ([x, y]) => [Math.round(x * P) / P, Math.round(y * P) / P]

const QUERY = `[out:json][timeout:90];
(
  relation["name:en"~"Temple Mount",i](31.770,35.230,31.784,35.242);
);
out geom;`

async function overpass() {
  if (existsSync(CACHE) && !REFETCH) {
    console.log('using scripts/.landmarks-cache.json (--refetch to bypass)')
    return JSON.parse(readFileSync(CACHE, 'utf8'))
  }
  const res = await fetch('https://overpass-api.de/api/interpreter', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-www-form-urlencoded',
      'User-Agent': 'jesus-world-atlas/1.0 (build script)',
      Accept: 'application/json',
    },
    body: new URLSearchParams({ data: QUERY }).toString(),
  })
  if (!res.ok) throw new Error(`Overpass ${res.status}`)
  const json = await res.json()
  writeFileSync(CACHE, JSON.stringify(json))
  return json
}

// Stitch an OSM multipolygon's unordered, arbitrarily-directed ways into rings.
function ringsFrom(members) {
  const pool = members.filter(m => m.geometry && m.role !== 'inner')
                      .map(m => m.geometry.map(p => [p.lon, p.lat]))
  const same = (a, b) => Math.abs(a[0] - b[0]) < 1e-7 && Math.abs(a[1] - b[1]) < 1e-7
  const rings = []
  while (pool.length) {
    let ring = pool.shift()
    let moved = true
    while (moved && !same(ring[0], ring.at(-1))) {
      moved = false
      for (let i = 0; i < pool.length; i++) {
        if (same(ring.at(-1), pool[i][0]))      { ring = ring.concat(pool[i].slice(1));                 pool.splice(i, 1); moved = true; break }
        if (same(ring.at(-1), pool[i].at(-1)))  { ring = ring.concat(pool[i].slice(0, -1).reverse());   pool.splice(i, 1); moved = true; break }
      }
    }
    if (ring.length > 3) { ring.push(ring[0]); rings.push(ring.map(round)) }
  }
  return rings
}

const j = await overpass()
const tm = j.elements.find(e => /temple mount/i.test(e.tags?.['name:en'] || e.tags?.name || ''))
if (!tm) throw new Error('Temple Mount not returned by Overpass')
const rings = ringsFrom(tm.members)

// Check the geometry against the published wall lengths before shipping it.
const pts = rings.flat()
const lons = pts.map(p => p[0]), lats = pts.map(p => p[1])
const wM = (Math.max(...lons) - Math.min(...lons)) * 111320 * Math.cos(31.778 * Math.PI / 180)
const hM = (Math.max(...lats) - Math.min(...lats)) * 110570
const plausible = wM > 300 && wM < 420 && hM > 460 && hM < 560
if (!plausible) throw new Error(`Temple Mount extent ${wM.toFixed(0)}×${hM.toFixed(0)} m is not the expected trapezoid`)

const out = {
  _readme: 'Generated by scripts/build-landmarks.mjs — do not hand-edit. Extant, surveyed structures only; reconstructions live in site-plans.json.',
  landmarks: [{
    id: 'temple-mount',
    name: 'The Temple Mount',
    cityId: 'jerusalem',
    period: 'extant',
    note: "Herod's platform, begun c. 20 BC. The retaining walls survive to their original courses, so this outline is the first-century one — the western wall runs 488 m, the north wall 315 m.",
    source: 'OpenStreetMap (ODbL); wall lengths after standard surveys of the Haram platform',
    rings,
  }],
}
writeFileSync(OUT, JSON.stringify(out))
console.log(`wrote ${OUT}`)
console.log(`  Temple Mount  ${rings.length} ring(s), ${pts.length} vertices`)
console.log(`  extent ${wM.toFixed(0)} × ${hM.toFixed(0)} m — trapezoid bbox, consistent with a 488 m west wall`)
